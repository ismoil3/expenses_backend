# Ҳарфҳо барои токенизатсия (кириллӣ + лотинӣ + ҳарфҳои тоҷикӣ)
_TOKEN_RE = re.compile(r"[^\W\d_]+", re.UNICODE)

# Ҳадди ақали дарозӣ барои мутобиқати оғозӣ («продукт» ↔ «продуктов»)
_PREFIX_MIN = 4

# калима → category_key (як бор сохта мешавад)
_INDEX: dict[str, str] = {}
for _key, _words in KEYWORDS.items():
    for _word in _words:
        _INDEX.setdefault(_word.lower(), _key)

_PREFIXABLE: list[tuple[str, str]] = sorted(
    ((w, k) for w, k in _INDEX.items() if len(w) >= _PREFIX_MIN),
    key=lambda pair: -len(pair[0]),
)


def match_category_key(description: str) -> str | None:
    """Категорияро аз рӯи луғат меёбад. Наёфт — `None`."""
    if not description:
        return None

    tokens = [t.lower() for t in _TOKEN_RE.findall(description)]
    if not tokens:
        return None

    # 1) мутобиқати дақиқ
    for token in tokens:
        key = _INDEX.get(token)
        if key:
            return key

    # 2) мутобиқати оғозӣ: «таксиро» → «такси», «продуктов» → «продукт»
    for token in tokens:
        if len(token) < _PREFIX_MIN:
            continue
        for word, key in _PREFIXABLE:
            if token.startswith(word) or word.startswith(token):
                return key

    return None
